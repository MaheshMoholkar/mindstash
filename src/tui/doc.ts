import { agentName } from '../adapters/index.js';
import { itemsOf } from '../cli/format.js';
import { actionable } from '../core/scan.js';
import type { Item, ScanResult } from '../core/types.js';
import type { Row } from './data.js';
import { RULE_LABEL } from './data.js';
import { CATEGORY_COLOR, theme } from './theme.js';
import { fit, fmt, pill, wrap, type Line } from './ui.js';

const blank: Line = { text: '' };

const KIND_COLOR: Record<Item['kind'], string> = {
  get memory() { return theme.accent; },
  get skill() { return theme.info; },
  get instructions() { return theme.accent2; },
  get index() { return theme.muted; },
};

/** A section heading with a rule. */
function section(title: string, width: number, color: string = theme.accent2): Line {
  const t = title.toUpperCase();
  return { text: t, segs: [{ text: t, color, bold: true }, { text: ' ' + '─'.repeat(Math.max(0, width - t.length - 1)), color: theme.rule }] };
}

/** "• reason", wrapped with a hanging indent. */
function bullets(text: string, width: number, mark = '•', color: string = theme.accent): Line[] {
  return wrap(text, width - 2).map((t, i) => ({ text: t, segs: [{ text: i ? '  ' : `${mark} `, color }, { text: t }] }));
}

function kv(label: string, value: string, color: string = theme.fg): Line {
  return { text: `${label} ${value}`, segs: [{ text: label.padEnd(9), color: theme.muted }, { text: value, color }] };
}

function body(i: Item): string {
  return (i.kind === 'skill' ? i.body || i.description || '' : i.body).replace(/^\s*\n/, '').trimEnd();
}

/** Why MindStash can or can't change an item, in one line. */
export function editability(i: Item): string {
  if (!i.readOnly) return i.kind === 'memory' || i.kind === 'skill' ? 'd delete · a archive · e edit' : 'e edit';
  if (i.source?.startsWith('plugin:')) return `managed by the ${i.source.slice(7)} plugin (use /plugin) · e view`;
  if (i.source === 'system') return 'bundled with Codex · e view';
  if (i.agent === 'codex' && (i.kind === 'memory' || i.kind === 'index')) return 'generated by Codex (use /memories there) · e edit';
  return 'e edit';
}

function itemHeading(i: Item): Line {
  return { text: i.name, bold: true };
}

function itemExcerpt(i: Item, width: number, maxLines: number): Line[] {
  const text = wrap(body(i), width - 2);
  const lines = text.slice(0, maxLines).map((text): Line => ({ text, gutter: true }));
  if (text.length > maxLines) lines.push({ text: '…', dim: true });
  return lines;
}

function itemBlock(i: Item, width: number, showName: boolean): Line[] {
  const out: Line[] = [
    ...(showName ? [itemHeading(i)] : []),
    {
      text: '',
      segs: [
        pill(i.kind, KIND_COLOR[i.kind]),
        { text: ' ' },
        { text: i.scope.label, color: theme.info },
        { text: ' · ', color: theme.muted },
        { text: agentName(i.agent), color: theme.accent2 },
        { text: ' · ', color: theme.muted },
        { text: `~${fmt(i.loadTokens)} tk/session`, color: theme.warn },
        ...(i.readOnly ? [{ text: ' · ', color: theme.muted }, { text: 'read-only', color: theme.error }] : []),
      ],
    },
  ];
  if (i.description && i.kind !== 'memory') out.push(...wrap(i.description, width).map((t) => ({ text: t, color: theme.info })));
  out.push(...itemExcerpt(i, width, 400));
  return out;
}

/** A short preview or a scrollable detail view for the current row. */
export function docFor(row: Row | undefined, r: ScanResult, width: number, full: boolean, fileCursor = 0): Line[] {
  if (!row) return [{ text: 'Nothing selected.', dim: true }];

  if (row.pair) {
    const p = row.pair;
    return [
      { text: '', segs: [{ text: '⇄ ', color: theme.error }, { text: `${p.a.name} ↔ ${p.b.name}`, bold: true, color: CATEGORY_COLOR.contradiction }] },
      { text: '', segs: [pill('needs check', theme.warn), { text: '  ' }, { text: p.cue, color: theme.warn }] },
      kv('shared', p.shared.join(', '), theme.info),
      blank,
      section(`A · ${p.a.name}`, width, theme.accent),
      ...wrap(p.a.snippet, width - 2).map((t) => ({ text: t, gutter: true })),
      kv('file', p.a.path, theme.muted),
      blank,
      section(`B · ${p.b.name}`, width, theme.accent),
      ...wrap(p.b.snippet, width - 2).map((t) => ({ text: t, gutter: true })),
      kv('file', p.b.path, theme.muted),
      blank,
      ...bullets('MindStash only finds candidates. Ask your agent to judge it: /mindstash (Claude Code) or $mindstash (Codex).', width, 'ℹ', theme.info),
    ];
  }

  if (row.folder) {
    const fo = row.folder;
    const out: Line[] = [section(`${fo.children.length} findings`, width)];
    for (const c of fo.children.slice(0, full ? 500 : 14)) {
      out.push({ text: c.primary, segs: [{ text: c.primary }, { text: `  ${c.tag}`, color: theme.muted }] });
    }
    if (fo.children.length > 14 && !full) out.push({ text: `… ${fo.children.length - 14} more`, dim: true });
    return out;
  }
  if (row.archived) {
    const a = row.archived;
    return [
      { text: '', segs: [{ text: '↓ ', color: theme.accent2 }, { text: a.name, bold: true, color: theme.accent }] },
      { text: '', segs: [pill(a.kind, theme.accent2), { text: ' ' }, { text: a.scope, color: theme.info }, { text: ` · archived ${a.at.slice(0, 10)}`, color: theme.muted }] },
      blank,
      section('Locations', width),
      kv('was at', a.from, theme.fg),
      kv('kept at', a.to, theme.muted),
      blank,
      ...bullets('R restore it · e open the archived copy', width, '↑', theme.ok),
    ];
  }

  if (row.group) {
    const g = row.group;
    const lines: Line[] = [
      { text: '', segs: [{ text: '▸ ', color: theme.accent }, { text: g.label, bold: true, color: theme.accent }] },
      {
        text: '',
        segs: [
          ...(g.memories ? [pill(`${g.memories} memories`, theme.accent), { text: ' ' }] : []),
          ...(g.skills ? [pill(`${g.skills} skills`, theme.info), { text: ' ' }] : []),
          { text: `~${fmt(g.tokens)} tk/session`, color: theme.warn },
        ],
      },
      ...(g.gone ? bullets('The project folder no longer exists.', width, '!', theme.warn) : []),
      blank,
      section('Contents', width),
    ];
    for (const i of g.items.slice(0, full ? 500 : 12)) {
      lines.push({ text: i.name });
    }
    if (g.items.length > 12 && !full) lines.push({ text: `… ${g.items.length - 12} more`, dim: true });
    lines.push(blank, { text: 'Enter opens this scope · h goes back', dim: true });
    return lines;
  }

  const out: Line[] = [];
  const f = row.finding;
  const items = row.item ? [row.item] : f ? itemsOf(f, r) : [];
  if (f) {
    const color = CATEGORY_COLOR[f.category] ?? theme.fg;
    const missingProject = f.rule === 'missing-project';
    const [firstReason, ...otherReasons] = f.reasons;
    const title = missingProject
      ? 'Project folder is missing'
      : (full || f.title === row.primary ? firstReason : f.title) ?? f.title;
    if (!full) {
      const confidenceColor = { high: theme.error, medium: theme.warn, low: theme.muted }[f.confidence];
      const issue = pill(missingProject ? 'project missing' : RULE_LABEL[f.rule] ?? f.rule, color);
      const confidence = pill(`${f.confidence} confidence`, confidenceColor);
      if (issue.text.length + confidence.text.length + 1 <= width) {
        out.push({ text: '', segs: [issue, { text: ' ' }, confidence] });
      } else {
        out.push({ text: '', segs: [issue] }, { text: '', segs: [confidence] });
      }
    }
    if (full || !missingProject) out.push(...wrap(title, width).map((text) => ({ text, bold: true, color })));
    if (missingProject && (full || row.item) && items[0]) {
      out.push(...wrap(items[0].scope.label, width).map((text) => ({ text, color: theme.info })));
    }
    if (full) {
      if (!missingProject) for (const reason of otherReasons) out.push(...bullets(reason, width));
      out.push({ text: `${f.confidence} confidence · ${f.id}`, dim: true });
    }
    if (items.length) out.push(blank);
  }
  if (!full) {
    if (f && items.length > 1) out.push(section('Files', width));
    out.push(...items.slice(0, 6).filter((item) => item.name !== row.primary).map(itemHeading));
    if (row.item && !f) out.push({ text: row.item.kind, dim: true });
    if (items.length > 6) out.push({ text: `… ${items.length - 6} more files`, dim: true });
    if (items.length === 1) {
      const excerpt = itemExcerpt(items[0]!, width, 3);
      if (f && excerpt.length) out.push(section('Excerpt', width));
      out.push(...excerpt);
    }
    if (items.length > 1) out.push(blank, { text: 'Enter to pick a file', color: theme.info });
    if (row.item && !f) out.push(blank, { text: '✓ Nothing flagged', color: theme.ok });
    return out;
  }

  if (items.length > 1) {
    // File picker: j/k choose a file, d / a / e act on just that one.
    const at = Math.min(fileCursor, items.length - 1);
    const actionWidth = 'read-only'.length;
    const nameWidth = width - actionWidth - 4;
    out.push(section('Files', width));
    items.forEach((i, n) => {
      const on = n === at;
      const hint = on && actionable(i) ? 'd delete' : i.readOnly ? 'read-only' : '';
      out.push({
        text: i.name,
        cursor: on,
        bg: on ? theme.cursor : undefined,
        segs: [
          { text: on ? '▌ ' : '  ', color: theme.accent },
          { text: fit(i.name, nameWidth), color: on ? theme.cursorFg : theme.fg, bold: on },
          { text: `  ${fit(hint, actionWidth)}`, color: on ? theme.cursorInfo : theme.muted },
        ],
      });
    });
    const excerpt = itemExcerpt(items[at]!, width, 12);
    if (excerpt.length) out.push(blank, section('Contents', width), ...excerpt);
    return out;
  }
  if (items[0]) out.push(...itemBlock(items[0], width, items[0].name !== row.primary));
  if (row.item && !f) out.push(blank, { text: '✓ Nothing flagged', color: theme.ok });
  return out;
}
